"""Recurring bookings ("series", "block bookings").

A series is one row in ``booking_series`` plus one ``bookings`` row per
occurrence, all pointing back via ``bookings.series_id``. We materialise every
occurrence up front (ADR 0005) instead of expanding a rule at query time,
because then availability, the exclusion constraint, cancellations and
invoicing all Just Work on ordinary booking rows.

Typical use: Thornbury Badminton Club, Tuesdays 19:00-21:00 in Hall A, every
week from September to July. That's ~44 rows.

Limits: max 52 occurrences per series (clubs renew each season), every 1-4
weeks. Staff can override the 52 with ``allow_long=True``.

!! KNOWN BUG (HP-503): occurrences are generated by adding whole weeks to the
!! first occurrence's *UTC* start. When a series crosses a clock change, every
!! occurrence after the change is an hour off in local time (19:00 becomes
!! 18:00 after the October change, 20:00 after the March one). See
!! docs/known-issues/bookings.md. The proper fix depends on ADR 0013 (store
!! local wall-clock + zone), which is still only proposed. Until then staff split
!! series at the changeover dates -- see docs/bookings/how-to-block-bookings.md.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta

from psycopg import Connection
from psycopg.rows import dict_row

from hallpass.bookings import lifecycle
from hallpass.bookings.models import BookingConflict, SeriesSpec
from hallpass.bookings.slots import validate_booking_window
from hallpass.core.audit import write_audit
from hallpass.core.clock import now_utc
from hallpass.core.errors import HallpassError, NotFound, ValidationError
from hallpass.core.tz import LONDON, local_day_bounds, local_to_utc
from hallpass.notifications.outbox import enqueue

log = logging.getLogger(__name__)

MAX_OCCURRENCES = 52


class SeriesRejected(HallpassError):
    def __init__(self, message: str, conflicts: list[datetime]):
        super().__init__(message)
        self.conflicts = conflicts


@dataclass(slots=True)
class SeriesResult:
    series_id: int
    booking_ids: list[int] = field(default_factory=list)
    skipped_conflict: list[date] = field(default_factory=list)
    skipped_closure: list[date] = field(default_factory=list)
    skipped_requested: list[date] = field(default_factory=list)


def _first_occurrence(spec: SeriesSpec) -> date:
    d = spec.first_date
    while d.isoweekday() != spec.weekday:
        d += timedelta(days=1)
    return d


def occurrence_windows(spec: SeriesSpec) -> list[tuple[datetime, datetime]]:
    """(starts_at, ends_at) in UTC for each occurrence, before any skipping.

    The first occurrence is converted from local time properly. The rest are
    first + n weeks *in UTC*, which is the DST bug described at the top of this
    file. A fix that does the arithmetic on local dates was tried in Feb 2026
    (Gareth's branch hp-503-local-dates) but it changes the stored times of
    existing series when they're extended, and the clubs' invoices were
    already out, so it was parked.
    """
    first_day = _first_occurrence(spec)
    if first_day > spec.last_date:
        return []

    first_start = local_to_utc(first_day, spec.start_time)
    length = timedelta(minutes=spec.duration_minutes)
    step = timedelta(weeks=spec.every_n_weeks)
    _, last_utc = local_day_bounds(spec.last_date)

    windows: list[tuple[datetime, datetime]] = []
    start = first_start
    n = 0
    while start < last_utc:
        windows.append((start, start + length))
        n += 1
        start = first_start + step * n  # TODO(HP-503): local-date arithmetic
    return windows


def _closures(conn: Connection, space_id: int, first: datetime, last: datetime) -> list[tuple[datetime, datetime]]:
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT bp.starts_at, bp.ends_at
            FROM blackout_periods bp
            JOIN spaces s ON s.id = %(space_id)s
            WHERE (bp.space_id = s.id OR (bp.space_id IS NULL AND bp.facility_id = s.facility_id))
              AND bp.withdrawn_at IS NULL
              AND tstzrange(bp.starts_at, bp.ends_at) && tstzrange(%(first)s, %(last)s)
            """,
            {"space_id": space_id, "first": first, "last": last},
        )
        return list(cur.fetchall())


def create_series(
    conn: Connection,
    spec: SeriesSpec,
    *,
    staff_id: int | None = None,
    skip_conflicts: bool = False,
    allow_long: bool = False,
) -> SeriesResult:
    """Create a block booking.

    ``skip_conflicts=False`` (org portal default): if any occurrence clashes
    with an existing booking, SeriesRejected lists the clashing dates and the
    caller's transaction must roll back (the API's db.transaction() does).
    The org-admin check is done by the API handler, not here (TODO, it should
    be here).

    ``skip_conflicts=True`` (staff screen): clashing dates are left out and
    reported back.

    Occurrences that fall inside a blackout are ALWAYS skipped and reported in
    the result -- but not stored anywhere except the audit_log detail. Whether
    skipping is right is an open question; see docs/bookings/blackouts-and-series.md.
    """
    if spec.organisation_id is None and staff_id is None:
        raise HallpassError("only organisations or staff can create a series")

    windows = occurrence_windows(spec)
    if not windows:
        raise ValidationError("series has no occurrences in that date range")
    if len(windows) > MAX_OCCURRENCES and not allow_long:
        raise ValidationError(f"series would have {len(windows)} sessions; the limit is {MAX_OCCURRENCES}")

    # Validate against the first one only; the rest are copies. (Which is
    # exactly why the DST shift isn't caught here -- the later occurrences
    # still land on :00/:30, just the wrong hour.)
    validate_booking_window(*windows[0], is_staff=staff_id is not None, is_organisation=True)

    closures = _closures(conn, spec.space_id, windows[0][0], windows[-1][1])

    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            INSERT INTO booking_series (space_id, organisation_id, resident_id, weekday,
                                        local_start_time, duration_minutes, first_date, last_date,
                                        every_n_weeks, notes, created_by_staff_id, created_at)
            VALUES (%(space_id)s, %(org)s, %(res)s, %(weekday)s, %(start_time)s, %(duration)s,
                    %(first)s, %(last)s, %(every)s, %(notes)s, %(staff)s, %(now)s)
            RETURNING id
            """,
            {
                "space_id": spec.space_id,
                "org": spec.organisation_id,
                "res": spec.resident_id,
                "weekday": spec.weekday,
                "start_time": spec.start_time,
                "duration": spec.duration_minutes,
                "first": spec.first_date,
                "last": spec.last_date,
                "every": spec.every_n_weeks,
                "notes": spec.notes,
                "staff": staff_id,
                "now": now_utc(),
            },
        )
        row = cur.fetchone()
        assert row is not None
        series_id = row["id"]

    result = SeriesResult(series_id=series_id)
    conflicts: list[datetime] = []

    for starts_at, ends_at in windows:
        local_day = starts_at.astimezone(LONDON).date()
        if local_day in spec.skip_dates:
            result.skipped_requested.append(local_day)
            continue
        if any(cs < ends_at and ce > starts_at for cs, ce in closures):
            result.skipped_closure.append(local_day)
            continue
        try:
            if spec.organisation_id is not None:
                b = lifecycle.book_on_account(
                    conn,
                    space_id=spec.space_id,
                    starts_at=starts_at,
                    ends_at=ends_at,
                    organisation_id=spec.organisation_id,
                    staff_id=staff_id,
                    series_id=series_id,
                )
            else:
                # Staff-made series for an individual resident (rare; the
                # piano lessons in Music Room 2). Treated as confirmed, paid
                # at the desk.
                b = _staff_resident_occurrence(conn, spec, series_id, starts_at, ends_at, staff_id)
            result.booking_ids.append(b.id)
        except BookingConflict:
            conflicts.append(starts_at)
            result.skipped_conflict.append(local_day)

    if conflicts and not skip_conflicts:
        raise SeriesRejected(f"{len(conflicts)} of {len(windows)} sessions clash", conflicts)

    write_audit(
        conn,
        actor_staff_id=staff_id,
        action="series.create",
        entity="booking_series",
        entity_id=series_id,
        detail={
            "created": len(result.booking_ids),
            "skipped_closure": [d.isoformat() for d in result.skipped_closure],
            "skipped_conflict": [d.isoformat() for d in result.skipped_conflict],
            "skipped_requested": [d.isoformat() for d in result.skipped_requested],
        },
    )
    # One email for the whole series, not one per week.
    enqueue(conn, template="series_confirmed", series_id=series_id)
    return result


def _staff_resident_occurrence(conn, spec, series_id, starts_at, ends_at, staff_id):
    from hallpass.billing.pricing import quote_price

    price = quote_price(
        conn,
        space_id=spec.space_id,
        starts_at=starts_at,
        ends_at=ends_at,
        resident_id=spec.resident_id,
        organisation_id=None,
    )
    return lifecycle._insert(
        conn,
        {
            "space_id": spec.space_id,
            "resident_id": spec.resident_id,
            "organisation_id": None,
            "series_id": series_id,
            "starts_at": starts_at,
            "ends_at": ends_at,
            "status": "confirmed",
            "price_pence": price.total_pence,
            "hold_expires_at": None,
            "now": now_utc(),
            "staff_id": staff_id,
        },
    )


def cancel_series(
    conn: Connection,
    series_id: int,
    *,
    from_date: date | None = None,
    reason: str = "customer",
    staff_id: int | None = None,
) -> list[int]:
    """Cancel every future occurrence (or every occurrence from ``from_date``).
    Returns the cancelled booking ids.

    Past occurrences are left alone. There's no "cancelled" flag on the
    series itself; a series with no future active bookings is over.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute("SELECT * FROM booking_series WHERE id = %s", (series_id,))
        s = cur.fetchone()
    if s is None:
        raise NotFound(f"series {series_id}")
    cutoff = now_utc()
    if from_date is not None:
        cutoff = max(cutoff, local_day_bounds(from_date)[0])

    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT id FROM bookings
            WHERE series_id = %s AND starts_at >= %s AND status IN ('held', 'confirmed')
            ORDER BY starts_at
            """,
            (series_id, cutoff),
        )
        ids = [r[0] for r in cur.fetchall()]

    for booking_id in ids:
        # One cancellation email per occurrence would be 30 emails; the club
        # gets a single series_cancelled instead.
        lifecycle.cancel(conn, booking_id, reason=reason, by_staff_id=staff_id, notify=False)

    write_audit(
        conn,
        actor_staff_id=staff_id,
        action="series.cancel",
        entity="booking_series",
        entity_id=series_id,
        detail={"cancelled": ids, "from_date": from_date.isoformat() if from_date else None},
    )
    enqueue(conn, template="series_cancelled", series_id=series_id)
    return ids


def extend_series(conn: Connection, series_id: int, new_last_date: date, *, staff_id: int | None = None) -> SeriesResult:
    """Renew a series for another season. Re-uses occurrence_windows, so it
    inherits HP-503: the new occurrences are computed from the ORIGINAL first
    date's UTC time, which might be in summer time. That's how Riverside FC
    ended up with 18:00 kick-offs on the Saturday after the October change.

    Also: org series only. A resident series (organisation_id NULL) blows up in
    book_on_account -- HP-622."""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute("SELECT * FROM booking_series WHERE id = %s FOR UPDATE", (series_id,))
        s = cur.fetchone()
    if s is None:
        raise NotFound(f"series {series_id}")
    if new_last_date <= s["last_date"]:
        raise ValidationError("new end date must be after the current one")

    spec = SeriesSpec(
        space_id=s["space_id"],
        organisation_id=s["organisation_id"],
        resident_id=s["resident_id"],
        weekday=s["weekday"],
        start_time=s["local_start_time"],
        duration_minutes=s["duration_minutes"],
        first_date=s["first_date"],
        last_date=new_last_date,
        every_n_weeks=s["every_n_weeks"],
    )
    _, already_until = local_day_bounds(s["last_date"])
    result = SeriesResult(series_id=series_id)
    for starts_at, ends_at in occurrence_windows(spec):
        if starts_at < already_until:
            continue
        try:
            b = lifecycle.book_on_account(
                conn,
                space_id=spec.space_id,
                starts_at=starts_at,
                ends_at=ends_at,
                organisation_id=spec.organisation_id,  # type: ignore[arg-type]
                staff_id=staff_id,
                series_id=series_id,
            )
            result.booking_ids.append(b.id)
        except BookingConflict:
            result.skipped_conflict.append(starts_at.astimezone(LONDON).date())

    with conn.cursor() as cur:
        cur.execute("UPDATE booking_series SET last_date = %s WHERE id = %s", (new_last_date, series_id))
    log.info("extended series %s to %s (+%d)", series_id, new_last_date, len(result.booking_ids))
    return result
